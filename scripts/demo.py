"""One-command local demo for the netops CLI.

Starts two local HTTP services (one healthy, one intentionally unhealthy),
generates a temporary YAML config, and runs the full validate -> health ->
collect -> report pipeline. The expected overall status is DEGRADED because
the metrics service is optional and failing.
"""

from __future__ import annotations

import json
import sys
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from netops.cli import main  # noqa: E402


class _Handler(BaseHTTPRequestHandler):
    status = 200
    service = "service"

    def do_GET(self) -> None:  # noqa: N802
        if self.path.startswith("/healthz"):
            payload = json.dumps({"service": self.service, "ok": self.status == 200})
            body = payload.encode()
            self.send_response(self.status)
            self.send_header("Content-Type", "application/json")
            self.send_header("Content-Length", str(len(body)))
            self.end_headers()
            self.wfile.write(body)
            return
        self.send_error(404)

    def log_message(self, *args: object) -> None:
        return


def _start(status: int, service: str) -> tuple[ThreadingHTTPServer, int]:
    handler = type(
        f"Handler_{service}",
        (_Handler,),
        {"status": status, "service": service},
    )
    server = ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server, server.server_address[1]


def main_demo() -> int:
    api, api_port = _start(200, "edge-api")
    metrics, metrics_port = _start(503, "metrics")
    try:
        demo_dir = ROOT / "artifacts" / "demo"
        demo_dir.mkdir(parents=True, exist_ok=True)
        log_path = demo_dir / "edge-api.log"
        log_path.write_text(
            "2026-08-10T09:58:01Z INFO edge-api path=/healthz status=200\n"
            "2026-08-10T09:58:02Z INFO edge-api path=/v1/orders status=200\n"
            "Authorization: Bearer demo-secret\n",
            encoding="utf-8",
        )
        config_path = demo_dir / "config.yaml"
        config_path.write_text(
            f"""version: 1
environment: demo
description: Generated by scripts/demo.py
defaults:
  timeout_seconds: 1.0
  retries: 1
  backoff_seconds: 0.05
  max_backoff_seconds: 0.1
services:
  - name: edge-api
    type: http
    url: http://127.0.0.1:{api_port}/healthz
    expected_status: 200
  - name: metrics
    type: http
    url: http://127.0.0.1:{metrics_port}/healthz
    expected_status: 200
    required: false
log_sources:
  - name: edge-api-log
    type: file
    path: edge-api.log
    max_lines: 50
  - name: host-summary
    type: command
    command: [{json.dumps(sys.executable)}, "-c", "print('kernel: demo diagnostics collected')"]
    max_lines: 20
report:
  title: Netops Local Demo Report
""",
            encoding="utf-8",
        )
        print("Starting demo pipeline...")
        print(f"  healthy API:  http://127.0.0.1:{api_port}/healthz")
        print(f"  failing API:  http://127.0.0.1:{metrics_port}/healthz (optional)")
        print()
        code = main(
            [
                "run",
                "--config",
                str(config_path),
                "--output",
                str(demo_dir / "run"),
                "--force",
                "--log-format",
                "text",
                "--log-level",
                "WARNING",
            ]
        )
        print()
        print(f"Demo exit code: {code} (1 = degraded is expected)")
        print(f"Report: {demo_dir / 'run' / 'report.md'}")
        return 0
    finally:
        api.shutdown()
        metrics.shutdown()
        api.server_close()
        metrics.server_close()


if __name__ == "__main__":
    raise SystemExit(main_demo())
